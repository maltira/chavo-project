import { z } from 'zod'

// требования к новому паролю; на входе их не проверяем: у старых аккаунтов пароль мог быть другим
export const PASSWORD_HINT = 'Минимум 8 символов, заглавная и строчная буква, спецсимвол'

export const newPasswordSchema = z
    .string()
    .min(8, 'Пароль должен быть не короче 8 символов')
    .max(72, 'Пароль должен быть не длиннее 72 символов')
    .regex(/\p{Lu}/u, 'Добавьте заглавную букву')
    .regex(/\p{Ll}/u, 'Добавьте строчную букву')
    .regex(/[^\p{L}\p{N}\s]/u, 'Добавьте спецсимвол, например ! или #')
